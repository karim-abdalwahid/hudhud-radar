class I18nEngine {
    constructor() {
        this.currentLang = this.detectLanguage();
    }

    detectLanguage() {
        const urlParams = new URLSearchParams(window.location.search);
        const qLang = urlParams.get('lang');
        if (qLang === 'en' || qLang === 'ar') {
            return qLang;
        }

        const stored = localStorage.getItem('hudhud_lang');
        if (stored === 'en' || stored === 'ar') {
            return stored;
        }

        const match = document.cookie.match(/(?:^|; )hudhud_lang=(en|ar)(?:;|$)/);
        if (match) {
            return match[1];
        }

        return 'en';
    }

    t(key, replacements = {}) {
        const dict = HUDHUD_TRANSLATIONS[this.currentLang] || HUDHUD_TRANSLATIONS['en'];
        let text = dict[key] || HUDHUD_TRANSLATIONS['en'][key] || key;
        for (const [k, v] of Object.entries(replacements)) {
            text = text.replace(new RegExp(`{${k}}`, 'g'), v);
        }
        return text;
    }

    setLanguage(lang) {
        if (lang !== 'en' && lang !== 'ar') return;
        this.currentLang = lang;
        localStorage.setItem('hudhud_lang', lang);
        document.cookie = `hudhud_lang=${lang};path=/;max-age=31536000;SameSite=Lax`;
        this.apply();
        window.dispatchEvent(new CustomEvent('hudhud_lang_change', { detail: { lang } }));
    }

    toggle() {
        const next = this.currentLang === 'en' ? 'ar' : 'en';
        this.setLanguage(next);
    }

    apply() {
        const isAr = this.currentLang === 'ar';
        document.documentElement.lang = this.currentLang;
        document.documentElement.dir = isAr ? 'rtl' : 'ltr';

        if (isAr) {
            document.body.style.fontFamily = "'Tajawal', 'Cairo', -apple-system, sans-serif";
        } else {
            document.body.style.fontFamily = "'Plus Jakarta Sans', 'Inter', -apple-system, sans-serif";
        }

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (translation) {
                el.textContent = translation;
            }
        });

        document.querySelectorAll('[data-i18n-html]').forEach(el => {
            const key = el.getAttribute('data-i18n-html');
            const translation = this.t(key);
            if (translation) {
                el.innerHTML = translation;
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = this.t(key);
            if (translation) {
                el.placeholder = translation;
            }
        });

        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const translation = this.t(key);
            if (translation) {
                el.title = translation;
            }
        });

        document.querySelectorAll('.lang-switcher-btn').forEach(btn => {
            btn.textContent = this.t('lang.switch_btn');
            btn.setAttribute('aria-label', `Switch to ${isAr ? 'English' : 'Arabic'}`);
        });
    }

    renderSwitcherButton() {
        const btn = document.createElement('button');
        btn.className = 'lang-switcher-btn';
        btn.type = 'button';
        btn.textContent = this.t('lang.switch_btn');
        btn.onclick = () => this.toggle();
        return btn;
    }
}

window.hudhudI18n = new I18nEngine();

document.addEventListener('DOMContentLoaded', () => {
    window.hudhudI18n.apply();
});
